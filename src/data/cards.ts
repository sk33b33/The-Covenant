export const CARDS: Card[] = [...figures, ...covenants, ...relics]

const BY_ID = new Map(CARDS.map((c) => [c.id, c]))

export const getCard = (id: string): Card | undefined => BY_ID.get(id)

/** Throws on an unknown id — used where a missing card is a bug, not a state. */
export function requireCard(id: string): Card {
  const card = BY_ID.get(id)
  if (!card) throw new Error(`Unknown card id: ${id}`)
  return card
}

export const CARDS_IN_SET = (setId: string) => CARDS.filter((c) => c.set === setId)
